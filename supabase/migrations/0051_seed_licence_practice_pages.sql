# B. Practice questions

This page provides practice questions covering the objectives in Child Development and Education Psychology (Heading B). The questions use the same format and command words as the Sindh Teaching Licence test.

## Practice questions

### CRQ 1

(15 marks) **Explain** the difference between Piaget's concept of assimilation and accommodation. **Illustrate** your answer with an example of a Class 2 pupil learning about different types of animals.

### CRQ 2

