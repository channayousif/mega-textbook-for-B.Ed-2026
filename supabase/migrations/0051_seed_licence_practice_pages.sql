# A. Practice: Methods of Teaching and Foundations of Education

This page follows the format of the licence paper's Part II: constructed-response questions (CRQs) worth
15 marks each and one extended-response case study (ERQ) worth 100 marks. Attempt each question under
time pressure before reading the rubric: about 5 minutes per CRQ and 50 minutes for the ERQ.

## Practice questions

### CRQ 1

(15 marks) A Class 6 teacher in Sukkur says: "Student-centred teaching is the modern way; direct
instruction should be abandoned." **Evaluate** this statement with reference to the purposes of
teacher-centred and student-centred instruction and the learning theories behind them. *(A01, A04)*

### CRQ 2

(15 marks) **Design** a 10-minute questioning sequence for a Class 5 lesson on "Why we should save
water". Include at least two closed and two open questions, label each with its Bloom's level, and
**explain** how you will use wait time and redirecting to involve the whole class of 50. *(A02, A05)*

### CRQ 3

(15 marks) **Explain** the five essential elements of cooperative learning and **show** how the STAD
model builds individual accountability and a fair incentive structure. *(A03)*

### CRQ 4

(15 marks) **Explain** John Dewey's principle of active learning and **compare** the role of the teacher
in a pragmatist classroom with the role of the teacher in an idealist classroom. *(A08)*

### CRQ 5

(15 marks) Using the functionalist, conflict and interactionist perspectives, **analyse** why children
from poor rural families in Sindh are more likely to leave school early. **Suggest** one action a teacher
can take in response to each perspective. *(A09)*

### CRQ 6

(15 marks) **Discuss** the obligations of the state and of the teacher toward religious minority pupils
in Pakistan, with reference to Islamic teaching and at least three articles of the Constitution. *(A07)*

### CRQ 7

(15 marks) **Write** a teaching philosophy statement of about 200 words for an elementary teacher. Name at
least one educational philosophy and one psychological perspective, and **justify** how they shape your
aims, methods and assessment. *(A08, A10)*

### CRQ 8

(15 marks) **Compare** the educational aims and methods of Darul Uloom Deoband and the Muhammadan
Anglo-Oriental College, Aligarh, and **explain** what the 18th Amendment (2010) changed about
responsibility for education in Pakistan. *(A11)*

### ERQ 1

(100 marks) **Read the case and answer all parts.**

Government Boys and Girls Primary School, in a village near Badin, has 310 pupils and six teachers. Mr
Aslam has taught Class 5 for eighteen years. His class has 58 pupils. Every lesson follows the same
pattern: he reads the textbook aloud, explains difficult words, writes questions and answers on the
board, and the pupils copy them. Pupils who cannot recite the answers the next day are made to stand at
the back. He calls on the same six pupils in the front row because "the others never know". Eight of
his pupils are Hindu; during the Islamiat period they sit silently at the back because there is no
other arrangement.

A new teacher, Miss Samina, joins the school after completing her B.Ed. She organises her Class 4 into
groups of four, starts each unit with a question from the pupils' lives, and uses short quizzes and
pair work. Some parents complain that her class is noisy and that "children are playing, not studying".
The head teacher, who must prepare the school for a district assessment in three months, asks both
teachers to present a plan for improving learning. Mr Aslam says he has no time for "new methods"
because the syllabus must be finished. Miss Samina admits that some groups waste time and that one or
two pupils do all the work in each group.

The head also reminds staff that under the provincial licensing policy they will need to show evidence
of their professional development and practice against the national standards.

Answer the following:

**(a)** (15 marks) **Identify** the instructional approach Mr Aslam uses and the philosophy and learning
theory it reflects. **Evaluate** its strengths and weaknesses for his class.

**(b)** (20 marks) **Analyse** Mr Aslam's questioning and his treatment of pupils who cannot recite
answers, using ideas from questioning strategy and the interactionist perspective. **Recommend**
specific improvements.

**(c)** (20 marks) Miss Samina's group work has problems. **Diagnose** them using the essential elements
of cooperative learning and **design** one improved cooperative lesson (name the model and its steps)
for her Class 4.

**(d)** (15 marks) **Discuss** the situation of the Hindu pupils during Islamiat in the light of the
Constitution of Pakistan and Islamic teaching, and **state** what the school should do.

**(e)** (15 marks) **Propose** a plan that combines direct and indirect instruction so that both
teachers prepare pupils for the district assessment without abandoning higher-order learning. Include
two objectives at different Bloom's levels.

**(f)** (15 marks) **Explain** which National Professional Standards for Teachers each teacher should
focus on, and what evidence each could collect for licence renewal.

