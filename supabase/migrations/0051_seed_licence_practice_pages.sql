(15 نمبر) دارالعلوم دیوبند اور محمڈن اینگلو اورینٹل کالج، علی گڑھ کے تعلیمی مقاصد اور طریقوں کا **موازنہ کریں**، اور
**وضاحت کریں** کہ اٹھارہویں ترمیم (2010) نے پاکستان میں تعلیم کی ذمہ داری کے بارے میں کیا بدلا۔ *(A11)*

### ERQ 1 - طویل جوابی سوال

(100 نمبر) **کیس پڑھیں اور تمام حصوں کے جواب دیں۔**

بدین کے قریب ایک گاؤں کے گورنمنٹ بوائز اینڈ گرلز پرائمری اسکول میں 310 شاگرد اور چھ اساتذہ ہیں۔ جناب اسلم اٹھارہ سال سے
جماعت پنجم پڑھا رہے ہیں۔ ان کی جماعت میں 58 شاگرد ہیں۔ ہر سبق ایک ہی انداز پر چلتا ہے: وہ درسی کتاب بلند آواز سے پڑھتے
ہیں، مشکل الفاظ کی وضاحت کرتے ہیں، تختے پر سوال و جواب لکھتے ہیں، اور شاگرد انھیں نقل کرتے ہیں۔ جو شاگرد اگلے دن جواب
زبانی نہیں سنا پاتے انھیں پیچھے کھڑا کر دیا جاتا ہے۔ وہ اگلی قطار کے انھی چھ شاگردوں کو بلاتے ہیں کیونکہ "باقی کبھی نہیں
جانتے"۔ ان کے آٹھ شاگرد ہندو ہیں؛ اسلامیات کے پیریڈ میں وہ خاموشی سے پیچھے بیٹھے رہتے ہیں کیونکہ کوئی اور انتظام نہیں۔

ایک نئی استانی، مس ثمینہ، بی ایڈ مکمل کرنے کے بعد اسکول میں آتی ہیں۔ وہ اپنی جماعت چہارم کو چار چار کے گروہوں میں منظم
کرتی ہیں، ہر یونٹ کا آغاز شاگردوں کی زندگی کے کسی سوال سے کرتی ہیں، اور مختصر کوئز اور جوڑیوں میں کام استعمال کرتی ہیں۔
کچھ والدین شکایت کرتے ہیں کہ ان کی جماعت میں شور ہوتا ہے اور "بچے پڑھ نہیں رہے، کھیل رہے ہیں"۔ صدر معلم، جنھیں تین ماہ
میں ضلعی جائزے کے لیے اسکول تیار کرنا ہے، دونوں اساتذہ سے تعلم بہتر بنانے کا منصوبہ پیش کرنے کو کہتے ہیں۔ جناب اسلم کہتے
ہیں کہ ان کے پاس "نئے طریقوں" کا وقت نہیں کیونکہ نصاب ختم کرنا ہے۔ مس ثمینہ تسلیم کرتی ہیں کہ کچھ گروہ وقت ضائع کرتے
ہیں اور ہر گروہ میں ایک دو شاگرد سارا کام کرتے ہیں۔

صدر معلم عملے کو یہ بھی یاد دلاتے ہیں کہ صوبائی لائسنس پالیسی کے تحت انھیں اپنی پیشہ ورانہ ترقی اور قومی معیارات کے
مقابلے میں اپنے عمل کا ثبوت دکھانا ہوگا۔

درج ذیل کے جواب دیں:

**(a)** (15 نمبر) جناب اسلم کے تدریسی طرزِ رسائی اور اس کے پیچھے فلسفے اور تعلمی نظریے کی **نشان دہی کریں**۔ ان کی
جماعت کے لیے اس کی خوبیوں اور خامیوں کی **جانچ کریں**۔

**(b)** (20 نمبر) سوال کرنے کی حکمتِ عملی اور تعاملی نقطۂ نظر کے خیالات استعمال کرتے ہوئے جناب اسلم کے سوال کرنے اور جواب
نہ سنا پانے والے شاگردوں سے ان کے برتاؤ کا **تجزیہ کریں**۔ مخصوص بہتری کی **سفارش کریں**۔

**(c)** (20 نمبر) مس ثمینہ کے گروہی کام میں مسائل ہیں۔ باہمی تعاون پر مبنی تعلم کے لازمی عناصر کی مدد سے ان کی
**تشخیص کریں** اور ان کی جماعت چہارم کے لیے ایک بہتر تعاونی سبق **ترتیب دیں** (ماڈل اور اس کے قدموں کا نام لیں)۔

**(d)** (15 نمبر) پاکستان کے آئین اور اسلامی تعلیمات کی روشنی میں اسلامیات کے دوران ہندو شاگردوں کی صورتِ حال پر **بحث
کریں**، اور **بتائیں** کہ اسکول کو کیا کرنا چاہیے۔

**(e)** (15 نمبر) ایسا منصوبہ **تجویز کریں** جو براہِ راست اور بالواسطہ تدریس کو ملائے تاکہ دونوں اساتذہ اعلیٰ سطح کے تعلم
کو چھوڑے بغیر شاگردوں کو ضلعی جائزے کے لیے تیار کریں۔ مختلف بلوم سطحوں پر دو مقاصد شامل کریں۔

**(f)** (15 نمبر) **وضاحت کریں** کہ ہر استاد کو کن قومی پیشہ ورانہ معیارات پر توجہ دینی چاہیے، اور لائسنس کی تجدید کے
لیے ہر ایک کیا ثبوت جمع کر سکتا ہے۔

