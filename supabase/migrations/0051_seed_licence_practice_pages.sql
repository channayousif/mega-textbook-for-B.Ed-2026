(15 نمبر) ایک استاد کا عقیدہ ہے کہ "تعلم استاد کا بچے تک علم منتقل کرنا ہے۔" **تجزیہ کریں (analyse)** کہ یہ
عقیدہ استاد کے معمولات، نشستوں اور بچوں کی غلطیوں پر ردِ عمل کے انتظام کو کیسے شکل دے گا، اور **شناخت کریں (identify)** کہ یہ کس نظریۂ تعلم پر سب سے زیادہ منحصر ہے، اور بتائیں کہ یہ عقیدہ کیا چھوڑ دیتا ہے۔ *(C01)*

