### ERQ 1

(100 marks) **Case Study:** 
You have recently been appointed as a Class 4 teacher in a government school in a rural district of Sindh. The classroom consists of 35 students with diverse backgrounds. You notice a student named Ali who consistently struggles with reading comprehension. Ali is often restless, frequently interrupts others, and becomes easily frustrated when asked to read aloud. During break times, he is observed sitting alone, and other students occasionally tease him. His parents work long hours in agriculture and are rarely able to attend school meetings.

You decide to develop a comprehensive plan to support Ali's learning and social-emotional development.

**a)** (20 marks) **Analyse** Ali's situation using Maslow's hierarchy of needs. Identify which levels of needs are currently unmet and explain how this impacts his classroom behaviour.

**b)** (25 marks) Drawing on Erikson's psychosocial theory, **explain** the developmental crisis Ali is likely facing at this age (Industry vs. Inferiority). **Discuss** how his current experiences might affect the resolution of this crisis.

**c)** (25 marks) **Design** an intervention plan using Vygotsky's concept of the Zone of Proximal Development (ZPD) to improve Ali's reading comprehension. Provide specific examples of scaffolding you would use.

**d)** (30 marks) **Evaluate** the role of the microsystem and mesosystem (from Bronfenbrenner's ecological model) in Ali's case. **Propose** practical steps you can take to strengthen the mesosystem despite his parents' work commitments.

