# D. Practice: assessment and test development

This page gives a full practice set for heading D in the format of the licence paper: constructed
response questions (CRQs) of 15 marks each and one case-study extended response question (ERQ) of
100 marks. Answer under timed conditions: about 5 minutes per CRQ and 50 minutes for the ERQ.
Then mark your work with the rubrics at the end.

## Practice questions

