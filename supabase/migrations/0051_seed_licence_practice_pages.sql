محترمہ شازیہ سے اگلی سہ ماہی میں اپنے کمرے کا انتظام بہتر بنانے کا تحریری منصوبہ مانگا ہے۔ وہ اس چلانے اور
باہر نکالنے کی طرف واپس نہیں جانا چاہتیں جس کے بچے عادی ہیں، مگر انہیں یقین نہیں کہ کہاں سے شروع کریں، اور
