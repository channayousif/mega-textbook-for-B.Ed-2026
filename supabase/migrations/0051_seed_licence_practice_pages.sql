# A. مشق: تدریسی طریقے اور تعلیم کی بنیادیں

یہ صفحہ لائسنس پرچے کے حصہ دوم کی طرز پر ہے: 15، 15 نمبر کے تعمیری جوابی سوال (CRQ) اور 100 نمبر کا ایک طویل جوابی
کیس اسٹڈی سوال (ERQ)۔ معیارِ جانچ پڑھنے سے پہلے ہر سوال وقت کی پابندی کے ساتھ حل کریں: ہر CRQ کے لیے تقریباً 5 منٹ اور
ERQ کے لیے 50 منٹ۔

## Practice questions

### CRQ 1 - تعمیری جوابی سوال

(15 نمبر) سکھر کا جماعت ششم کا ایک استاد کہتا ہے: "طالب علم مرکز تدریس جدید طریقہ ہے؛ براہِ راست تدریس ترک کر دینی
چاہیے۔" استاد مرکز اور طالب علم مرکز تدریس کے مقاصد اور ان کے پیچھے تعلمی نظریات کے حوالے سے اس بیان کی **جانچ کریں**۔
*(A01، A04)*

### CRQ 2 - تعمیری جوابی سوال

(15 نمبر) جماعت پنجم کے سبق "ہمیں پانی کیوں بچانا چاہیے" کے لیے 10 منٹ کا سوالات کا سلسلہ **ترتیب دیں**۔ کم از کم دو
بند اور دو کھلے سوال شامل کریں، ہر ایک پر بلوم کی سطح لکھیں، اور **وضاحت کریں** کہ 50 کی پوری جماعت کو شامل کرنے کے لیے
آپ انتظار کا وقفہ اور رخ موڑنا کیسے استعمال کریں گے۔ *(A02، A05)*

### CRQ 3 - تعمیری جوابی سوال

(15 نمبر) باہمی تعاون پر مبنی تعلم کے پانچ لازمی عناصر کی **وضاحت کریں** اور **دکھائیں** کہ STAD ماڈل انفرادی جواب دہی
اور منصفانہ ترغیبی ڈھانچا کیسے بناتا ہے۔ *(A03)*

### CRQ 4 - تعمیری جوابی سوال

(15 نمبر) جان ڈیوی کے فعال تعلم کے اصول کی **وضاحت کریں** اور نتائجیت پسند جماعت میں استاد کے کردار کا تصوریت پسند
جماعت میں استاد کے کردار سے **موازنہ کریں**۔ *(A08)*

### CRQ 5 - تعمیری جوابی سوال

(15 نمبر) وظیفی، تصادمی اور تعاملی نقطۂ نظر استعمال کرتے ہوئے **تجزیہ کریں** کہ سندھ کے غریب دیہی خاندانوں کے بچوں کے
جلدی اسکول چھوڑنے کا امکان زیادہ کیوں ہے۔ ہر نقطۂ نظر کے جواب میں استاد کا ایک اقدام **تجویز کریں**۔ *(A09)*

### CRQ 6 - تعمیری جوابی سوال

(15 نمبر) اسلامی تعلیمات اور آئین کے کم از کم تین آرٹیکلز کے حوالے سے پاکستان میں مذہبی اقلیتی شاگردوں کے بارے میں
ریاست اور استاد کی ذمہ داریوں پر **بحث کریں**۔ *(A07)*

### CRQ 7 - تعمیری جوابی سوال

(15 نمبر) ایک ابتدائی استاد کے لیے تقریباً 200 الفاظ کا تدریسی فلسفے کا بیان **لکھیں**۔ کم از کم ایک تعلیمی فلسفے اور
ایک نفسیاتی نقطۂ نظر کا نام لیں، اور **جواز دیں** کہ یہ آپ کے مقاصد، طریقوں اور تشخیص کو کیسے شکل دیتے ہیں۔ *(A08، A10)*

