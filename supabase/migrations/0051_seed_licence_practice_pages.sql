- **Criteria:** 5 marks for defining a relevant social interaction concept (e.g., cooperation, exchange, symbolic interaction), 15 marks for proposing practical trust-building steps.
- **Answer:** Ms. Fatima must use positive social interaction (cooperation and accommodation) rather than conflict. She can start by listening actively to the parents' fears without dismissing them. By demonstrating respect for their cultural roots (symbolic interaction), she can carefully explain the curriculum, highlighting elements that align with local values and ethics. She could invite parents to sit in on a lesson, making the process transparent. Building interpersonal trust through consistent, respectful, and culturally sensitive communication will slowly reduce suspicion.

**4. Reactivating the SMC (20 marks)**
