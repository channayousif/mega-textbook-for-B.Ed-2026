# C. Practice: Classroom Management

These questions follow the format of Part II of the Sindh Teaching Licence test: constructed-response
questions (CRQs) worth 15 marks each, and one extended-response case study (ERQ) worth 100 marks.
Attempt each question in writing, under time, before you read the marking guidance at the end. In the real
test, Part II gives 50 minutes for ten CRQs (about 5 minutes each) and 50 minutes for the ERQ, so
once you know the material, practise at that pace.

## Practice questions

### CRQ 1

(15 marks) A teacher believes that "learning is the teacher transferring knowledge to the pupil."
**Analyse** how that belief would shape the teacher's management of routines, seating and responses to
pupils' errors, **identify** which learning theory it draws on most heavily, and state what the belief
leaves out. *(C01)*

### CRQ 2

(15 marks) A trainee's observation record reads: "The teacher praised the pupils who answered
correctly and moved on when a pupil gave a wrong answer." **Write** two defensible inferences from this
observation, **explain** why each might be wrong, and **describe** what further data you would collect to
decide between them. *(C03)*

### CRQ 3

(15 marks) Take the objective "pupils will be able to add two-digit numbers with carrying." **Plan** it
for three settings: a single-grade class of 25, a multigrade room with Classes 2 to 4, and a single-grade
class of 60. For each, **state** one curriculum or management decision that changes because of the room
and **explain** why. *(C05, C10)*

### CRQ 4

(15 marks) A teacher says: "I told my class the routine on the first day, so now they know it."
**Explain** what this overlooks, using the course guide's account of how routines are established, and
**design** a routine for the transition from whole-class explanation to group work, including how you would
teach it. *(C06)*

### CRQ 5

(15 marks) A school in Badin invites parents to an annual prize day and asks them for donations, but
never consults them about anything else. **Distinguish** between community participation and community
involvement, and **propose** two practices that would move this school towards involvement, **justifying**
each. *(C07)*

### CRQ 6

(15 marks) **Evaluate** the claim that "a caring response to classroom disruption is a weak response."
Refer to the difference between punitive and restorative consequences and to the six-step response to a
behaviour breakdown. *(C07, C09)*

### ERQ 1

(100 marks)

**Case study.** Miss Shazia has just been posted to a government primary school in a village near
Mirpurkhas. She teaches Classes 3 and 4 together in one room: 52 pupils on fixed benches built for 35,
one blackboard, a locked cupboard of science materials, and walls with a few faded commercial charts.
The previous teacher kept order mainly by shouting and by making pupils stand outside the room. On her
first day Miss Shazia notices that the same five Class 4 boys in the front row answer every question,
while the back benches, most of them Class 3 girls, say nothing all day. When she tries group work in
her second week, pupils argue over who holds the single textbook, noise rises quickly, and two boys
start pushing each other. A Class 3 girl who has recently moved from Karachi finishes every task within
minutes and then chats with her neighbours. Some parents have told the head teacher they are unhappy
that their daughters are "not learning anything" and are thinking of keeping them at home. The head
teacher has asked Miss Shazia for a written plan to improve management in her room over the next term.
She wants to avoid returning to the shouting and exclusion her pupils are used to, but she is not sure
where to start, and she has no budget.

Answer all parts.

**(a)** Using the course guide's definition of classroom management, **explain** why the previous
teacher's classroom was not well managed even if it was quiet. (15 marks)

**(b)** **Identify** four features of Miss Shazia's physical and social environment that are causing
management problems, and **propose** a no-cost change for each. (20 marks)

**(c)** **Design** a schedule for one 40-minute lesson for her multigrade room and **describe** two routines,
one of them for group work, that would make it run. (20 marks)

**(d)** **Explain** how Miss Shazia could differentiate one lesson objective for the early finisher and
for pupils who are struggling, without lowering the target. (15 marks)

**(e)** Two boys push each other during group work. **Apply** a caring, accountable response and
**justify** it against sending them outside. (15 marks)

**(f)** **Suggest** how Miss Shazia could involve the concerned parents so that they become partners
rather than critics. (15 marks)

