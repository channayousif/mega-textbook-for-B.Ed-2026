# E. Practice questions

## E. Practice questions

### CRQ 1

A common misconception is treating the terms 'society' and 'community' as interchangeable when discussing the social context of schooling. 

1. **Define** the term 'society' in a sociological context. (4 marks)
2. **Explain** how a 'community' differs from a 'society'. (6 marks)
3. **Describe** one way a school serves the specific needs of its local community rather than the broader society. (5 marks)

### CRQ 2

Culture is not biologically inherited; it is passed down through generations via socialisation.

1. **Identify** and **explain** two key characteristics of culture (e.g., culture is learned, shared, symbolic, or dynamic). (8 marks)
2. **Suggest** how a teacher can use the 'symbolic' nature of culture to create an inclusive classroom environment. (7 marks)

### CRQ 3

Pakistan is a multi-cultural society with distinct regional, linguistic, and ethnic identities. 

1. **Describe** how regional cultural diversity might manifest in a public school classroom in Karachi. (6 marks)
2. **Analyse** the potential challenges a teacher faces when their own cultural background differs significantly from that of their students. (9 marks)

### CRQ 4

A teacher's working context is shaped by systemic factors such as transfers, physical school conditions, and social status.

1. **Explain** how unpredictable teacher transfers negatively impact the school-community relationship. (7 marks)
2. **Justify** the need for improving the social status of the teaching profession in Pakistan, giving two specific benefits to the education system. (8 marks)

### CRQ 5

A primary school in rural Sindh has deteriorating physical infrastructure and low student attendance. The head teacher decides to actively involve the local community to address these issues.

1. **Identify** three barriers that might prevent parents from participating in school improvement efforts. (6 marks)
2. **Propose** three practical strategies the head teacher can use to encourage active community involvement in the school. (9 marks)

### ERQ 1

Ms. Fatima has recently been appointed as a primary school teacher in a remote agricultural village in the Sukkur district. When she arrives, she finds the school building in disrepair, with no boundary wall and a lack of clean drinking water. The village community is close-knit, deeply traditional, and primarily engaged in farming. 

During her first month, Ms. Fatima notices that attendance drops by half during the wheat harvest season. When she visits the absent students' homes, the parents are polite but firmly explain that the children's labour is essential for the family's survival. They also express mild suspicion about the new curriculum, fearing it might distance their children from their cultural and religious roots. The school's School Management Committee (SMC) officially exists on paper but has not held a meeting in three years, as the local elders feel the school is the government's responsibility, not theirs.

Despite feeling overwhelmed by the poor physical working context and the social resistance, Ms. Fatima is determined to improve the educational outcomes for the children in the village. 

1. **Analyse** the interaction between the family as an economic institution and the school as an educational institution in this scenario. (20 marks)
2. **Evaluate** the impact of the school's physical working context (disrepair, no boundary wall) on Ms. Fatima's motivation and the community's perception of the school. (20 marks)
3. **Apply** the principles of social interaction to propose how Ms. Fatima can build trust with the parents regarding the new curriculum. (20 marks)
4. **Design** a step-by-step plan for Ms. Fatima to reactivate the dormant School Management Committee (SMC), ensuring the inclusion of local opinion makers. (20 marks)
5. **Justify** Ms. Fatima's potential role as an agent of social change in this village, explaining how she can balance respecting traditional culture with promoting educational advancement. (20 marks)

