**5. Role as an agent of social change (20 marks)**
- **Criteria:** 10 marks for defining the role of a change agent in this context, 10 marks for explaining the balance between tradition and progress.
- **Answer:** A teacher is a key agent of social change by introducing new ideas, promoting equity, and breaking cycles of poverty through education. However, Ms. Fatima cannot impose change aggressively; she must act as a bridge. She balances this by honouring local traditions (e.g., dressing appropriately, respecting elders) while gently challenging harmful practices (like long-term absenteeism). By linking educational advancement to the community's own goals (e.g., better farming techniques, local development, preserving their culture through literacy), she facilitates organic, sustainable social change from within rather than alienating the community.
