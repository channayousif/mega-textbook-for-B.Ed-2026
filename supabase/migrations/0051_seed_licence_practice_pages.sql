# مشقی سوالات

## Practice questions

### CRQ 1

عموماً اسکولی تناظر میں 'معاشرہ' اور 'برادری' کو ہم معنی سمجھا جاتا ہے جو کہ غلط ہے۔

1. عمرانیات کے تناظر میں لفظ 'معاشرہ' (society) کی **تعریف** کریں۔ (4 نمبر)
2. **وضاحت** کریں کہ ایک 'برادری' (community) ایک 'معاشرے' سے کیسے مختلف ہے۔ (6 نمبر)
3. **بیان** کریں کہ کیسے ایک اسکول وسیع تر معاشرے کے بجائے اپنی مقامی برادری کی مخصوص ضروریات پوری کرتا ہے۔ (5 نمبر)

### CRQ 2

ثقافت حیاتیاتی طور پر وراثت میں نہیں ملتی؛ یہ سماجی کاری کے ذریعے نسل در نسل منتقل ہوتی ہے۔

1. ثقافت کی دو اہم خصوصیات کی **شناخت** اور **وضاحت** کریں (جیسے ثقافت سیکھی جاتی ہے، مشترک ہوتی ہے، علامتی ہوتی ہے)۔ (8 نمبر)
2. **تجویز** کریں کہ ایک استاد ثقافت کی 'علامتی' نوعیت کو استعمال کرتے ہوئے کلاس روم کا شراکتی ماحول کیسے بنا سکتا ہے۔ (7 نمبر)

### CRQ 3

پاکستان ایک کثیر الثقافتی معاشرہ ہے جس کی الگ الگ علاقائی، لسانی، اور نسلی شناختیں ہیں۔

1. **بیان** کریں کہ علاقائی ثقافتی تنوع کراچی کے ایک سرکاری اسکول کی کلاس میں کیسے ظاہر ہو سکتا ہے۔ (6 نمبر)
2. ان ممکنہ چیلنجز کا **تجزیہ** کریں جن کا ایک استاد کو سامنا کرنا پڑتا ہے جب اس کا اپنا ثقافتی پس منظر اس کے طلباء سے نمایاں طور پر مختلف ہو۔ (9 نمبر)

### CRQ 4

ایک استاد کے کام کا سیاق و سباق نظامی عوامل جیسے تبادلوں، اسکول کے طبعی حالات اور سماجی حیثیت سے تشکیل پاتا ہے۔

1. **وضاحت** کریں کہ کیسے غیر متوقع اساتذہ کے تبادلے اسکول اور برادری کے تعلقات کو منفی طور پر متاثر کرتے ہیں۔ (7 نمبر)
2. پاکستان میں تدریسی پیشے کی سماجی حیثیت کو بہتر بنانے کی ضرورت کا **جواز** پیش کریں اور نظامِ تعلیم کے لیے دو مخصوص فوائد بتائیں۔ (8 نمبر)

### CRQ 5

دیہی سندھ کے ایک پرائمری اسکول کا بنیادی ڈھانچہ خستہ حال ہے اور طلباء کی حاضری کم ہے۔ ہیڈ ٹیچر ان مسائل کو حل کرنے کے لیے مقامی برادری کو فعال طور پر شامل کرنے کا فیصلہ کرتا ہے۔

1. ان تین رکاوٹوں کی **شناخت** کریں جو والدین کو اسکول کی بہتری کی کوششوں میں حصہ لینے سے روک سکتی ہیں۔ (6 نمبر)
2. ہیڈ ٹیچر کے لیے ایسی تین عملی حکمت عملیاں **تجویز** کریں جن سے وہ برادری کو اسکول کے معاملات میں فعال طور پر شامل کر سکے۔ (9 نمبر)

### ERQ 1

محترمہ فاطمہ کو حال ہی میں ضلع سکھر کے ایک دور دراز زرعی گاؤں میں پرائمری اسکول کی استانی کے طور پر تعینات کیا گیا ہے۔ جب وہ وہاں پہنچتی ہیں، تو دیکھتی ہیں کہ اسکول کی عمارت خستہ حال ہے، کوئی چار دیواری نہیں ہے اور پینے کے صاف پانی کی کمی ہے۔ گاؤں کی برادری ایک دوسرے سے بہت جڑی ہوئی، گہری روایتی، اور بنیادی طور پر کھیتی باڑی سے وابستہ ہے۔

