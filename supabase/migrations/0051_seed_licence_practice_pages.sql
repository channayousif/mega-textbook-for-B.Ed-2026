### ERQ 1

**Case study: Government Boys and Girls Primary School, near Hyderabad**

Mr Imran teaches Class 5 in a government primary school near Hyderabad. His class has 54 pupils,
many of whom speak Sindhi at home and study science in Urdu. The school holds a monthly test and a
final examination; the monthly test counts towards promotion.

Mr Imran writes each monthly science test the night before. His latest test had 25 true-false
items, most copied word for word from the first chapter of the textbook, although he had taught three
chapters. The directions said only "Attempt all questions." He marked the papers, wrote a total on
each, and read the marks aloud in class from highest to lowest. Eleven pupils scored below 10 out of
25. Several parents complained that their children "knew the work but could not understand the
questions." Mr Imran keeps no record of which questions pupils got wrong, so he cannot say which
topics need re-teaching, and pupils receive no comments on their papers, only the total.

The head teacher has attended a district workshop on the National Professional Standards for
Teachers and wants the school to move towards "assessment for learning". She asks Mr Imran to
redesign next month's assessment of the unit on plants, which he will teach over eight periods. She
also asks him to suggest how the school could judge pupils' progress through the year more fairly
than by a single monthly score. He has no printing budget beyond the usual test paper, and the
classroom has no cupboards.

Answer all parts.

(a) **Identify** the weaknesses in Mr Imran's current test and marking practice, naming the principle
of testing each one violates. *(20 marks)*

(b) **Design** a table of specifications for a 20-item test on the plants unit, and **explain** how it
improves the test's validity. *(20 marks)*

(c) **Explain** how Mr Imran should reduce the language barrier for his pupils without lowering the
level of the science being tested. *(15 marks)*

(d) **Propose** two formative assessment strategies Mr Imran can use during the eight periods, with
the feedback he will give. *(20 marks)*

(e) **Evaluate** whether a portfolio or regular performance tasks would help the school judge progress
more fairly, given its constraints, and **recommend** a practical approach linked to NPST Standard 5.
*(25 marks)*

