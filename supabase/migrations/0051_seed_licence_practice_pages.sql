  - **Step 2:** One-on-one outreach. Visit these leaders personally to discuss the school's physical state (e.g., the boundary wall), framing it as a community safety and pride issue rather than a government failure.
  - **Step 3:** Restructuring the committee. Organise a general meeting and formally invite these influential figures to take leadership roles in the SMC, ensuring representation from the parents.
